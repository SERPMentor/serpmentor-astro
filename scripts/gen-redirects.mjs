/**
 * Prebuild step: generate public/_redirects (read by Cloudflare Pages and
 * Netlify) so every old WordPress URL 301s to its new home, and every route
 * with a trailing slash 301s to the slash-free version.
 *
 * Old WordPress used flat post URLs (serpmentor.com/best-ai-seo-tools/).
 * The Astro site nests them under the category (/seo/best-ai-seo-tools).
 */
import { writeFile, readFile } from "node:fs/promises";
import path from "node:path";

const WP_URL = "https://cms.serpmentor.com";
const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "public", "_redirects");

const HIDE = new Set(["sample-post-test", "hello-world", "auto-draft"]);

// Routes that exist on the new site. Their /path/ form must 301 to /path.
const PILLARS = ["tech", "backlinks", "news", "tools", "ai-optimization"].map(
  (s) => `/seo/${s}`,
);
const PAGES = [
  "/about",
  "/services",
  "/coaching",
  "/hire-seo-specialist",
  "/local-seo-services",
  "/careers",
  "/privacy",
  "/terms",
  "/blog",
  "/resources",
  "/reviews",
  "/contact",
  "/newsletter-success",
];
// old WordPress page slugs -> new clean paths (also in astro.config.mjs)
const OLD_PAGES = {
  "/about-us": "/about",
  "/seo-specialist-service": "/hire-seo-specialist",
  "/career": "/careers",
  "/privacy-policy": "/privacy",
  "/terms-and-conditions": "/terms",
};

const HEADER = "# generated by scripts/gen-redirects.mjs — do not hand-edit\n\n";

function trailingSlashRules(routes) {
  return routes.map((r) => `${r}/   ${r}   301`).join("\n");
}

async function fromWordPress() {
  const res = await fetch(`${WP_URL}/graphql`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      query: `{
        posts(first: 200) { nodes { slug categories { nodes { slug } } } }
        categories(first: 100) { nodes { slug count } }
      }`,
    }),
  });
  const json = await res.json();
  const posts = json?.data?.posts?.nodes ?? [];
  const cats = json?.data?.categories?.nodes ?? [];
  if (!posts.length) throw new Error("no posts returned");

  const BACKLINKS_CATS = new Set(["seo-backlinks", "backlinks", "link-building"]);

  const catSlugs = cats
    .filter((c) => c.count && !BACKLINKS_CATS.has(c.slug)) // backlinks -> /seo/backlinks
    .map((c) => `/${c.slug}`);

  const postLines = ["\n# old flat post URLs -> category-nested"];
  for (const n of posts) {
    if (HIDE.has(n.slug)) continue;
    const cat = n.categories?.nodes?.[0]?.slug ?? "articles";
    // link-building posts nest under the backlinks pillar
    const to = BACKLINKS_CATS.has(cat) ? `/seo/backlinks/${n.slug}` : `/${cat}/${n.slug}`;
    postLines.push(`/${n.slug}    ${to}    301`);
    postLines.push(`/${n.slug}/   ${to}    301`);
    postLines.push(`/blog/${n.slug}    ${to}    301`);
    postLines.push(`/blog/${n.slug}/   ${to}    301`);
    if (BACKLINKS_CATS.has(cat)) {
      // and the interim /seo-backlinks/{slug} URLs
      postLines.push(`/seo-backlinks/${n.slug}    ${to}    301`);
      postLines.push(`/seo-backlinks/${n.slug}/   ${to}    301`);
    }
  }
  // catch-all for the old /seo-backlinks archive and anything under it
  postLines.push("/seo-backlinks    /seo/backlinks    301");
  postLines.push("/seo-backlinks/*    /seo/backlinks/:splat    301");

  return { postBlock: postLines.join("\n") + "\n", catSlugs };
}

async function main() {
  let postBlock = "";
  let catSlugs = ["/seo", "/seo-backlinks", "/linkedin", "/case-study"];

  try {
    const wp = await fromWordPress();
    postBlock = wp.postBlock;
    catSlugs = wp.catSlugs;
  } catch (e) {
    console.warn(`gen-redirects: ${e.message} — keeping existing _redirects if present`);
    try {
      await readFile(OUT);
      return;
    } catch {
      /* no fallback file; write what we can */
    }
  }

  const oldPageLines = Object.entries(OLD_PAGES)
    .flatMap(([from, to]) => [`${from}    ${to}    301`, `${from}/   ${to}    301`])
    .join("\n");

  const out =
    HEADER +
    "# old WordPress category archives\n" +
    "/category/*    /:splat    301\n\n" +
    "# old WordPress tag pages and feeds\n" +
    "/tag/*    /blog    301\n" +
    "/feed    /blog    301\n" +
    "/feed/*    /blog    301\n\n" +
    "# old WordPress page slugs\n" +
    oldPageLines +
    "\n" +
    postBlock +
    "\n# trailing slash -> no trailing slash (known routes)\n" +
    trailingSlashRules([...PAGES, ...PILLARS, ...catSlugs]) +
    "\n";

  await writeFile(OUT, out);
  const count = (out.match(/ 301$/gm) || []).length;
  console.log(`gen-redirects: wrote public/_redirects (${count} rules)`);
}

await main();
