/**
 * Prebuild step: generate public/_redirects (read by Cloudflare Pages and
 * Netlify) plus bulk-redirects.csv (for Cloudflare Bulk Redirects).
 *
 * Cloudflare Pages caps _redirects rules whose source has no matching build
 * file ("dynamic" rules) at 100. So _redirects only holds a handful of
 * wildcards and the fixed old-page slugs. The per-post flat URLs
 * (serpmentor.com/{slug} -> /{category}/{slug}) are handled two ways instead:
 *   1. src/pages/[...oldpost].astro emits a real redirect page at /{slug}
 *      for every published post (works with zero _redirects rules).
 *   2. bulk-redirects.csv lists the same mappings as true 301s to load into
 *      Cloudflare dashboard -> Bulk Redirects (optional but better for SEO).
 * /blog/{slug} old URLs are handled by src/pages/blog/[slug].astro stubs, and
 * /seo-backlinks/{slug} by the /seo-backlinks/* wildcard below.
 */
import { writeFile, readFile } from "node:fs/promises";
import path from "node:path";

const WP_URL = "https://cms.serpmentor.com";
const SITE = "https://serpmentor.com";
const ROOT = path.resolve(import.meta.dirname, "..");
const OUT = path.join(ROOT, "public", "_redirects");
const CSV_OUT = path.join(ROOT, "bulk-redirects.csv");

const HIDE = new Set(["sample-post-test", "hello-world", "auto-draft"]);
const BACKLINKS_CATS = new Set(["seo-backlinks", "backlinks", "link-building"]);
// slugs with a hand-built page at /seo/backlinks/{slug} (mirror of
// BACKLINKS_STATIC_SLUGS in src/lib/posts.ts)
const BACKLINKS_STATIC_SLUGS = new Set([
  "uk-posting-sites", "dating-posting-sites", "lifestyle-posting-sites",
  "finance-posting-sites", "real-estate-posting-sites",
  "gadget-posting-sites", "usa-posting-sites",
  "cybersecurity-posting-sites", "italy-posting-sites",
  "igaming-posting-sites",
]);

// Routes that exist on the new site. Their /path/ form should 301 to /path.
const PILLARS = ["tech", "backlinks", "news", "tools", "ai-optimization"].map(
  (s) => `/seo/${s}`,
);
const PAGES = [
  "/about", "/services", "/coaching", "/hire-seo-specialist",
  "/local-seo-services", "/careers", "/privacy", "/terms", "/blog",
  "/resources", "/reviews", "/contact", "/newsletter-success", "/website-design",
];
// old WordPress page slugs -> new clean paths (also in astro.config.mjs)
const OLD_PAGES = {
  "/about-us": "/about",
  "/seo-specialist-service": "/hire-seo-specialist",
  "/career": "/careers",
  "/privacy-policy": "/privacy",
  "/terms-and-conditions": "/terms",
};

const HEADER = "# generated by scripts/gen-redirects.mjs — do not hand-edit\n\n";
const trailingSlashRules = (routes) =>
  routes.map((r) => `${r}/   ${r}   301`).join("\n");

async function fromWordPress() {
  const res = await fetch(`${WP_URL}/graphql`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({
      query: `{
        posts(first: 500) { nodes { slug categories { nodes { slug } } } }
        categories(first: 100) { nodes { slug count } }
      }`,
    }),
  });
  const json = await res.json();
  const posts = json?.data?.posts?.nodes ?? [];
  const cats = json?.data?.categories?.nodes ?? [];
  if (!posts.length) throw new Error("no posts returned");

  const catSlugs = cats
    .filter((c) => c.count && !BACKLINKS_CATS.has(c.slug))
    .map((c) => `/${c.slug}`);

  // per-post mappings for the Bulk Redirects CSV (NOT for _redirects)
  const csvRows = [];
  for (const n of posts) {
    if (HIDE.has(n.slug)) continue;
    const cat = n.categories?.nodes?.[0]?.slug ?? "articles";
    const to =
      BACKLINKS_STATIC_SLUGS.has(n.slug) || BACKLINKS_CATS.has(cat)
        ? `/seo/backlinks/${n.slug}`
        : `/${cat}/${n.slug}`;
    csvRows.push([`${SITE}/${n.slug}`, `${SITE}${to}`, 301]);
    csvRows.push([`${SITE}/blog/${n.slug}`, `${SITE}${to}`, 301]);
  }

  return { catSlugs, csvRows };
}

async function main() {
  let catSlugs = ["/seo", "/linkedin", "/case-study"];
  let csvRows = [];

  try {
    const wp = await fromWordPress();
    catSlugs = wp.catSlugs;
    csvRows = wp.csvRows;
  } catch (e) {
    console.warn(`gen-redirects: ${e.message} — keeping existing files if present`);
    try {
      await readFile(OUT);
      return;
    } catch {
      /* no fallback file; write what we can */
    }
  }

  const oldPageLines = Object.entries(OLD_PAGES)
    .flatMap(([from, to]) => [`${from}    ${to}    301`, `${from}/   ${to}    301`])
    .join("\n");

  // _redirects: wildcards + fixed slugs only. ~4 rules count as "dynamic".
  const out =
    HEADER +
    "# old WordPress category archives, tags and feeds\n" +
    "/category/*    /:splat    301\n" +
    "/tag/*    /blog    301\n" +
    "/feed    /blog    301\n" +
    "/feed/*    /blog    301\n\n" +
    "# link-building posts: /seo-backlinks/... -> /seo/backlinks/...\n" +
    "/seo-backlinks    /seo/backlinks    301\n" +
    "/seo-backlinks/*    /seo/backlinks/:splat    301\n\n" +
    "# old WordPress page slugs\n" +
    oldPageLines +
    "\n\n# trailing slash -> no trailing slash (known routes)\n" +
    trailingSlashRules([...PAGES, ...PILLARS, ...catSlugs]) +
    "\n\n# NOTE: per-post flat URLs (/{slug}, /blog/{slug}) are handled by\n" +
    "# src/pages/[...oldpost].astro + src/pages/blog/[slug].astro redirect\n" +
    "# pages, and by bulk-redirects.csv (Cloudflare -> Bulk Redirects).\n";

  await writeFile(OUT, out);
  const dyn = (out.match(/^\/\S*[:*]\S*\s/gm) || []).length;
  console.log(`gen-redirects: wrote public/_redirects (${dyn} dynamic rules)`);

  if (csvRows.length) {
    const csv =
      "source,target,status\n" +
      csvRows.map((r) => r.join(",")).join("\n") +
      "\n";
    await writeFile(CSV_OUT, csv);
    console.log(`gen-redirects: wrote bulk-redirects.csv (${csvRows.length} rows)`);
  }
}

await main();
